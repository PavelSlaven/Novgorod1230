const EXPECTED_POST_COMMIT_FAILURES = new Set([
  'LLM_TURN_BUDGET_EXHAUSTED',
  'TURN_NARRATION_REJECTED',
  'TRACE_PHASE_2_PRESENTATION_INVALID',
  'TRACE_PHASE_2_NARRATION_IN_PROGRESS',
  'TRACE_PHASE_2_NARRATION_REJECTED'
]);

export function isExpectedPostCommitPresentationFailure(error) {
  return EXPECTED_POST_COMMIT_FAILURES.has(error?.code);
}

import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { canonicalDigest } from '@rus/materialization';
import { buildGate1OwnerDataArtifacts,
  validateGate1OwnerDataAuthoringAttestation } from
  './generate-gate1-owner-data-requests.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const gate1Root = resolve(root,
  'data/world-catalogs/novgorod/runtime-catalog/gate1-owner-data-v1');
const outputRoot = resolve(gate1Root, 'seed-closure-v1');
const importerRoot = resolve(root,
  'tools/rus13-world-base-importer/world_base_importer_v1');
const paths = Object.freeze({
  archive: resolve(root, 'data/world-base-sources/rus13-base-v1.tar.gz'),
  archiveManifest: resolve(root,
    'data/world-base-sources/rus13-base-v1.manifest.json'),
  importer: resolve(importerRoot, 'scripts/import_world_base.py'),
  config: resolve(importerRoot, 'config/world_base_import_manifest_v1.json'),
  seed: resolve(importerRoot, 'world_base_seed_v1.sql.gz'),
  report: resolve(importerRoot, 'reports/world_base_import_report_v1.json')
});

const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));
const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const fileBinding = async (path) => ({
  path: path.slice(root.length + 1).replaceAll('\\', '/'),
  sha256: sha256(await readFile(path))
});
const noAuthority = () => Object.freeze({
  approval_attestation_present: false,
  seed_derivation_authorized: false,
  import_authorized: false,
  activation_authorized: false,
  production_authorized: false,
  existing_party_migration_authorized: false,
  runtime_item_creation_authorized: false
});

export async function buildGate1SeedClosureArtifacts({ tableClosure }) {
  const [ownerArtifacts, ownerAttestation, archiveManifest, report,
    archive, archiveManifestSource, importer, config, seed, reportSource] =
    await Promise.all([
      buildGate1OwnerDataArtifacts(),
      readJson(resolve(gate1Root, 'authoring-approval-attestation.json')),
      readJson(paths.archiveManifest), readJson(paths.report),
      fileBinding(paths.archive), fileBinding(paths.archiveManifest),
      fileBinding(paths.importer), fileBinding(paths.config),
      fileBinding(paths.seed), fileBinding(paths.report)
    ]);
  validateGate1OwnerDataAuthoringAttestation({ ...ownerArtifacts,
    attestation: ownerAttestation });
  if (archive.sha256 !== archiveManifest.archive.sha256
      || archive.sha256 !== ownerArtifacts.parent.source_snapshot.sha256
      || report.errors.length !== 0 || report.warnings.length !== 0) {
    throw new Error('GATE1_SEED_DERIVATION_SOURCE_INVALID');
  }
  const seedBytes = await readFile(paths.seed);
  const sql = gunzipSync(seedBytes);
  const header = '-- Generated by RUS13 world_base importer v1\n'
    + '-- Generated at: 2026-07-06T00:00:00Z\n';
  if (!sql.toString('utf8', 0, header.length).startsWith(header)) {
    throw new Error('GATE1_SEED_DERIVATION_NONDETERMINISTIC_HEADER');
  }
  const tables = tableClosure;
  const expectedTables = Object.keys(report.summary.tables).sort();
  const totalRows = tables.reduce((total, table) => total + table.row_count, 0);
  if (tables.length !== 30 || totalRows !== 42577
      || tables.some(({ payload_sha256: digest }) =>
        !/^[a-f0-9]{64}$/u.test(digest))
      || tables.some(({ table, row_count: rowCount }) =>
        report.summary.tables[table]?.rows !== rowCount)
      || canonicalDigest(tables.map(({ table }) => table).sort()) !==
        canonicalDigest(expectedTables)) {
    throw new Error('GATE1_SEED_DERIVATION_CLOSURE_INVALID');
  }
  const candidateCore = {
    schema: 'rus.gate1_rus13_seed_closure_candidate.v1',
    status: 'pending_independent_authoring_approval',
    operation: 'derive_deterministic_rus13_seed_and_full_table_closure',
    approved_owner_binding: Object.freeze({
      parent_request_digest: ownerArtifacts.parent.request_digest,
      parent_attestation_digest: ownerAttestation.attestation_digest,
      archive, archive_manifest: archiveManifestSource
    }),
    derivation_inputs: Object.freeze({ importer, config,
      deterministic_generated_at: '2026-07-06T00:00:00Z' }),
    derived_outputs: Object.freeze({ seed,
      uncompressed_sql_sha256: sha256(sql), report: reportSource,
      total_row_count: totalRows, table_count: tables.length,
      table_closure: Object.freeze(tables),
      table_closure_digest: canonicalDigest(tables) }),
    authority: noAuthority()
  };
  const candidate = Object.freeze({ ...candidateCore,
    candidate_digest: canonicalDigest(candidateCore) });
  const requestCore = {
    schema: 'rus.gate1_rus13_seed_closure_request.v1',
    status: 'pending_independent_authoring_approval',
    decision_requested:
      'approve_exact_seed_derivation_and_transactional_full_closure_readback',
    candidate_digest: candidate.candidate_digest,
    requested_scope: Object.freeze({
      seed_gzip_sha256: seed.sha256,
      seed_sql_sha256: candidate.derived_outputs.uncompressed_sql_sha256,
      report_sha256: reportSource.sha256,
      total_row_count: totalRows,
      table_count: tables.length,
      table_closure_digest:
        candidate.derived_outputs.table_closure_digest,
      exact_all_table_readback_required: true,
      transactional_import_only: true,
      grants_runtime_activation: false
    }),
    authority: noAuthority()
  };
  const request = Object.freeze({ ...requestCore,
    request_digest: canonicalDigest(requestCore) });
  const artifacts = Object.freeze({ candidate, request });
  validatePendingGate1SeedClosure(artifacts);
  return artifacts;
}

export async function loadGate1SeedClosureArtifacts() {
  const artifacts = {
    candidate: await readJson(resolve(outputRoot, 'candidate.json')),
    request: await readJson(resolve(outputRoot, 'request.json'))
  };
  validatePendingGate1SeedClosure(artifacts);
  const [seed, report] = await Promise.all([
    fileBinding(paths.seed), fileBinding(paths.report)
  ]);
  if (artifacts.candidate.derived_outputs.seed.sha256 !== seed.sha256
      || artifacts.candidate.derived_outputs.report.sha256 !== report.sha256) {
    throw new Error('GATE1_SEED_CLOSURE_SOURCE_BINDING_INVALID');
  }
  return Object.freeze(artifacts);
}

export function validatePendingGate1SeedClosure({ candidate, request }) {
  if (candidate.schema !== 'rus.gate1_rus13_seed_closure_candidate.v1'
      || request.schema !== 'rus.gate1_rus13_seed_closure_request.v1'
      || candidate.status !== 'pending_independent_authoring_approval'
      || request.status !== 'pending_independent_authoring_approval'
      || candidate.derived_outputs.table_count !== 30
      || candidate.derived_outputs.total_row_count !== 42577
      || candidate.derived_outputs.table_closure.length !== 30
      || canonicalDigest(candidate.derived_outputs.table_closure) !==
        candidate.derived_outputs.table_closure_digest
      || candidate.derived_outputs.table_closure.some((table, index, tables) =>
        !Array.isArray(table.order_columns)
        || table.order_columns.length === 0
        || table.table !== [...tables].sort((left, right) =>
          left.table.localeCompare(right.table))[index].table
        || table.excluded_mutable_columns.some((column) =>
          !['created_at', 'updated_at'].includes(column)))
      || request.candidate_digest !== candidate.candidate_digest
      || request.requested_scope.table_closure_digest !==
        candidate.derived_outputs.table_closure_digest
      || request.requested_scope.exact_all_table_readback_required !== true
      || request.requested_scope.grants_runtime_activation !== false) {
    throw new Error('GATE1_SEED_CLOSURE_INVALID');
  }
  for (const artifact of [candidate, request]) {
    if (Object.values(artifact.authority).some((value) => value !== false)) {
      throw new Error('GATE1_SEED_CLOSURE_AUTHORITY_FORBIDDEN');
    }
  }
  const { candidate_digest: candidateDigest, ...candidateCore } = candidate;
  const { request_digest: requestDigest, ...requestCore } = request;
  if (candidateDigest !== canonicalDigest(candidateCore)
      || requestDigest !== canonicalDigest(requestCore)) {
    throw new Error('GATE1_SEED_CLOSURE_DIGEST_INVALID');
  }
  return true;
}

export function validateGate1SeedClosureAttestation({ candidate, request,
  attestation }) {
  validatePendingGate1SeedClosure({ candidate, request });
  const authority = attestation?.authority ?? {};
  if (attestation?.schema !==
      'rus.gate1_rus13_seed_closure_authoring_approval_attestation.v1'
      || attestation.status !==
        'approved_seed_derivation_and_transactional_full_closure_readback'
      || attestation.candidate_digest !== candidate.candidate_digest
      || attestation.request_digest !== request.request_digest
      || canonicalDigest(attestation.approved_scope) !==
        canonicalDigest(request.requested_scope)
      || authority.approval_attestation_present !== true
      || authority.seed_derivation_authorized !== true
      || authority.import_authorized !== true
      || authority.transactional_import_readback_only !== true
      || authority.exact_all_table_readback_required !== true
      || authority.activation_authorized !== false
      || authority.production_authorized !== false
      || authority.existing_party_migration_authorized !== false
      || authority.old_save_rematerialization_authorized !== false
      || authority.authoring_only_functional_allocation_runtime_selection
        !== false
      || authority.runtime_item_creation_authorized !== false) {
    throw new Error('GATE1_SEED_CLOSURE_ATTESTATION_INVALID');
  }
  const { attestation_digest: claimed, ...core } = attestation;
  if (claimed !== canonicalDigest(core)) {
    throw new Error('GATE1_SEED_CLOSURE_ATTESTATION_DIGEST_INVALID');
  }
  return true;
}


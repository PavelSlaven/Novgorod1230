import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { parseCsv } from "../../data/world-catalogs/novgorod/game-base-v1/nature-materials-weather/_shared/scripts/lib.mjs";

const TEST_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(TEST_DIR, "../..");
const GENERATOR_PATH = path.join(TEST_DIR, "generate-personal-names.mjs");
const SOURCE_PATH = path.join(ROOT_DIR, "data/world-catalogs/novgorod/game-base-v1/names-peoples/personal_names/name_pool_entries.csv");
const TRACKED_OUTPUT_PATH = path.join(TEST_DIR, "dev-world/personal-names.generated.json");
const POOL_ID = "novgorod_1230_1250_personal_names_v1";

function sortIds(left, right) {
  return left.id < right.id ? -1 : left.id > right.id ? 1 : 0;
}

function projectFromSource() {
  const sourceRows = parseCsv(fs.readFileSync(SOURCE_PATH, "utf8"));
  const selected = sourceRows.filter((row) => row.name_pool_id === POOL_ID && row.selection_class === "ordinary");
  return {
    male: selected.filter((row) => row.sex_category === "male").sort(sortIds),
    female: selected.filter((row) => row.sex_category === "female").sort(sortIds),
  };
}

function expectedModJson(rowsBySex) {
  return [
    {
      type: "snippet",
      category: "<male_full_name>",
      text: rowsBySex.male.map((row) => row.name_form),
      override: true,
    },
    {
      type: "snippet",
      category: "<female_full_name>",
      text: rowsBySex.female.map((row) => row.name_form),
      override: true,
    },
  ];
}

function runGenerator(args) {
  return spawnSync(process.execPath, [GENERATOR_PATH, ...args], {
    cwd: ROOT_DIR,
    encoding: "utf8",
  });
}

test("projects the real ordinary name rows into deterministic CDDA snippets", (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "personal-names-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));

  const outputPath = path.join(directory, "personal-names.generated.json");
  const rowsBySex = projectFromSource();
  assert.equal(rowsBySex.male.length, 166);
  assert.equal(rowsBySex.female.length, 42);

  const result = runGenerator(["--output", outputPath]);
  assert.equal(result.status, 0, result.stderr);

  const actualBytes = fs.readFileSync(outputPath);
  const expectedBytes = Buffer.from(`${JSON.stringify(expectedModJson(rowsBySex), null, 2)}\n`, "utf8");
  assert.deepEqual(actualBytes, expectedBytes, "generated bytes must match the direct CSV projection");
  assert.deepEqual(actualBytes, fs.readFileSync(TRACKED_OUTPUT_PATH), "generated bytes must match the checked-in dev-world file");

  const actual = JSON.parse(actualBytes.toString("utf8"));
  const rowsByCategory = new Map([
    ["<male_full_name>", rowsBySex.male],
    ["<female_full_name>", rowsBySex.female],
  ]);
  for (const snippet of actual) {
    assert.equal(snippet.type, "snippet");
    assert.equal(snippet.override, true);
    const selectedNames = new Set(rowsByCategory.get(snippet.category).map((row) => row.name_form));
    for (const nameForm of snippet.text) {
      assert.ok(selectedNames.has(nameForm), `${nameForm} must occur in a matching selected CSV row`);
    }
  }
});

test("--check compares exact bytes and reports stale output", (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "personal-names-check-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));

  const outputPath = path.join(directory, "personal-names.generated.json");
  const rowsBySex = projectFromSource();
  fs.writeFileSync(outputPath, `${JSON.stringify(expectedModJson(rowsBySex), null, 2)}\n`, "utf8");

  const current = runGenerator(["--check", "--output", outputPath]);
  assert.equal(current.status, 0, current.stderr);

  fs.appendFileSync(outputPath, " ");
  const stale = runGenerator(["--check", "--output", outputPath]);
  assert.notEqual(stale.status, 0);
  assert.match(stale.stderr, /stale/);
});
